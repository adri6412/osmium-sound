package Plugins::OsmiumConvert::Plugin;

# Osmium Convert — the one mechanism behind the appliance's per-player
# conversion control (Off / PCM upsampling / DSD).
#
# The appliance no longer writes custom-convert.conf itself. Instead the box
# that owns a player's settings sends this plugin a CLI command over the
# standard LMS port 9000 (jsonrpc.js / cometd), to whichever Lyrion that player
# follows — local, a remote Osmium, or a third-party server that has the plugin
# installed:
#
#   osmiumconvert set   <mac> dsd <dsd64|dsd128|dsd256> <clans-8|sdm-8>
#   osmiumconvert set   <mac> pcm <x2|x4|max>           <cap-hz>
#   osmiumconvert clear <mac>
#   osmiumconvert status                      -> rules + this server's SoX caps
#
# The plugin keeps the rules in its own prefs (so they survive a restart and no
# longer depend on boot order), writes them into its own custom-convert.conf,
# and reloads the conversion tables with no server restart. Each rule hands the
# decoded PCM to the portable Bin/osmium-convert helper, which execs SoX
# (sox_ng + sdm for DSD; any sox for PCM upsampling).
#
# Trust: set/clear are accepted only for a MAC that is a player currently
# connected to this server, so a client can only configure a real player.

use strict;
use warnings;

use base qw(Slim::Plugin::Base);

use File::Basename qw(dirname);
use File::Spec::Functions qw(catdir catfile);

use Slim::Utils::Log;
use Slim::Utils::Prefs;
use Slim::Control::Request;

my $log = Slim::Utils::Log->addLogCategory({
	category     => 'plugin.osmiumconvert',
	defaultLevel => 'WARN',
	description  => 'PLUGIN_OSMIUMCONVERT',
});

my $prefs = preferences('plugin.osmiumconvert');

# ── The rule template, kept byte-for-byte in step with hifi_squeezelite.py's
#    lms_rules(): same types, same decoders, same capability lines. DSD players
#    come out as DSF, PCM-upsampling players as FLAC (self-describing rate).
my $DECODE_FLAC_CAPS   = '# IFT:{START=--skip=%t}U:{END=--until=%v}';
my $DECODE_FLAC_CMD    = '[flac] -dcs $START$ $END$ -- $FILE$';
my $DECODE_FFMPEG_CAPS = '# IFT:{START=-ss %s}U:{END=-to %u}';
my $DECODE_FFMPEG_CMD  = '[ffmpeg] -v error -nostdin $START$ $END$ -i $FILE$ -map 0:a:0 -ac 2 -c:a pcm_s32le -f wav -';
my $SPOTTY_CAPS        = '# RT:{START=--start-position %s}';
my $SPOTTY_CMD         = '[spotty] -n Squeezebox -c "$CACHE$" --single-track $URL$ --bitrate 320 --disable-discovery --disable-audio-cache $START$';

# [ [type, caps, decode-command], ... ] — flac first, then everything ffmpeg
# decodes best. Spotty (raw) is handled apart because it feeds `raw`, not `wav`.
my @LMS_TYPES = (['flc', $DECODE_FLAC_CAPS, $DECODE_FLAC_CMD]);
push @LMS_TYPES, [$_, $DECODE_FFMPEG_CAPS, $DECODE_FFMPEG_CMD]
	for qw(wav aif alc alcx aac mp4 mp4x mp3 ogg ogf ops wma wmal wmap wvp wvpx ape mpc);

my $CONF_HEADER = "# Osmium Convert -- generated by the OsmiumConvert plugin, do not edit\n";

my $DSD_MODES = { dsd64 => 1, dsd128 => 1, dsd256 => 1 };
my $FILTERS   = { 'clans-8' => 1, 'sdm-8' => 1 };
my $MULTS     = { x2 => 1, x4 => 1, max => 1 };

sub initPlugin {
	my $class = shift;
	$class->SUPER::initPlugin(@_);

	Slim::Control::Request::addDispatch(
		['osmiumconvert', 'set', '_mac', '_mode', '_a', '_b'], [0, 0, 0, \&setCommand]);
	Slim::Control::Request::addDispatch(
		['osmiumconvert', 'clear', '_mac'], [0, 0, 0, \&clearCommand]);
	Slim::Control::Request::addDispatch(
		['osmiumconvert', 'status'], [0, 1, 0, \&statusQuery]);

	# Re-apply whatever was configured before this (re)start, independent of
	# the order services came up in.
	_apply();

	my $caps = _capabilities();
	$log->info(sprintf('Osmium Convert ready: sox=%s sox_ng=%s sdm=%s',
		$caps->{sox} // '-', $caps->{sox_ng} // '-', $caps->{sdm} ? 'yes' : 'no'));

	return 1;
}

sub shutdownPlugin { }

# ── Where this plugin lives (writable, scanned) and the helper it runs ──
sub _pluginDir {
	my $f = $INC{'Plugins/OsmiumConvert/Plugin.pm'};
	return $f ? dirname($f) : undef;
}

sub _confPath   { my $d = _pluginDir(); $d ? catfile($d, 'custom-convert.conf') : undef }
sub _helperPath { my $d = _pluginDir(); $d ? catfile($d, 'Bin', 'osmium-convert') : undef }

# The command that runs the helper. python3, not a bare path, so a lost exec
# bit (plugin unzipped on a third-party server) does not matter.
sub _helperCmd {
	my $args = shift;
	my $h = _helperPath() or return undef;
	return qq{python3 '$h' $args};
}

# ── Rules ───────────────────────────────────────────────────────────
# $rules = { "<mac>" => { kind => 'dsd'|'pcm', a => ..., b => ... } }
sub _rules { $prefs->get('rules') || {} }

sub _ruleBlock {
	my $rules = shift;
	my @lines;
	for my $mac (sort keys %$rules) {
		my $r = $rules->{$mac};
		my ($dst, $args);
		if ($r->{kind} eq 'dsd') {
			$dst  = 'dsf';
			$args = "dsd $r->{a} $r->{b}";
		}
		else {
			$dst  = 'flc';
			$args = "pcm $r->{a} $r->{b}";
		}
		my $wav = _helperCmd("$args wav");
		my $raw = _helperCmd("$args raw");
		next unless $wav && $raw;
		for my $t (@LMS_TYPES) {
			my ($typ, $caps, $decode) = @$t;
			push @lines, "$typ $dst * $mac", "\t$caps", "\t$decode | $wav";
		}
		push @lines, "spt $dst * $mac", "\t$SPOTTY_CAPS", "\t$SPOTTY_CMD | $raw";
	}
	return @lines ? join("\n", @lines) . "\n" : '';
}

# Write our conf and reload the conversion tables with no server restart.
sub _apply {
	my $path = _confPath();
	unless ($path) {
		$log->error('Osmium Convert: cannot locate plugin dir, not applying');
		return;
	}

	my $text = $CONF_HEADER . _ruleBlock(_rules());
	my $ok = eval {
		open(my $fh, '>', $path) or die "open $path: $!";
		print {$fh} $text;
		close($fh);
		1;
	};
	unless ($ok) {
		$log->error("Osmium Convert: writing $path failed: $@ "
			. '(is the plugin installed in a writable directory?)');
		return;
	}

	_reload();
}

# Clear the accumulated tables, then let LMS rebuild them from every convert
# file (server-level and every plugin's, ours included). loadConversionTables()
# alone would *add* duplicate profiles on each call; clearing first makes it a
# clean reload.
sub _reload {
	my $ok = eval {
		no warnings 'once';   # cross-package globals, defined in TranscodingHelper
		%Slim::Player::TranscodingHelper::commandTable  = ();
		%Slim::Player::TranscodingHelper::capabilities  = ();
		%Slim::Player::TranscodingHelper::binaries      = ();
		Slim::Player::TranscodingHelper::loadConversionTables();
		1;
	};
	$log->error("Osmium Convert: table reload failed: $@") unless $ok;
}

# ── SoX capabilities of this server (for the UI to gate DSD) ─────────
sub _capabilities {
	my $cmd = _helperCmd('--probe') or return { sox => undef, sox_ng => undef, sdm => 0 };
	my $json = '';
	eval {
		open(my $p, '-|', "$cmd 2>/dev/null") or die $!;
		local $/;
		$json = <$p>;
		close($p);
		1;
	};
	my $caps = eval { Slim::Utils::Misc::jsonToObj($json) } if $json;
	$caps = eval { require JSON::XS; JSON::XS::decode_json($json) } if !$caps && $json;
	return { sox => undef, sox_ng => undef, sdm => 0 } unless ref $caps eq 'HASH';
	return {
		sox    => $caps->{sox},
		sox_ng => $caps->{sox_ng},
		sdm    => $caps->{sdm} ? 1 : 0,
	};
}

# ── CLI: the appliance talks to us here ─────────────────────────────
sub _macOf {
	my $request = shift;
	my $mac = lc($request->getParam('_mac') // '');
	$mac =~ s/-/:/g;
	return $mac =~ /^([0-9a-f]{2}:){5}[0-9a-f]{2}$/ ? $mac : undef;
}

# A client may only configure a player that is currently connected here.
sub _connected {
	my $mac = shift;
	return Slim::Player::Client::getClient($mac) ? 1 : 0;
}

sub setCommand {
	my $request = shift;

	my $mac = _macOf($request);
	unless ($mac && _connected($mac)) {
		$log->warn('osmiumconvert set: unknown or not-connected player');
		return $request->setStatusBadParams();
	}

	my $mode = $request->getParam('_mode') // '';
	my $a    = $request->getParam('_a') // '';
	my $b    = $request->getParam('_b') // '';
	my $rules = { %{ _rules() } };

	if ($mode eq 'off') {
		delete $rules->{$mac};
	}
	elsif ($mode eq 'dsd') {
		unless ($DSD_MODES->{$a} && $FILTERS->{$b}) {
			return $request->setStatusBadParams();
		}
		my $caps = _capabilities();
		unless ($caps->{sox_ng} && $caps->{sdm}) {
			$request->addResult('error', 'noServerTools');
			return $request->setStatusDone();
		}
		$rules->{$mac} = { kind => 'dsd', a => $a, b => $b };
	}
	elsif ($mode eq 'pcm') {
		unless ($MULTS->{$a}) {
			return $request->setStatusBadParams();
		}
		my $cap = ($b =~ /^\d+$/) ? $b : 0;
		my $caps = _capabilities();
		unless ($caps->{sox}) {
			$request->addResult('error', 'noServerTools');
			return $request->setStatusDone();
		}
		$rules->{$mac} = { kind => 'pcm', a => $a, b => $cap };
	}
	else {
		return $request->setStatusBadParams();
	}

	$prefs->set('rules', $rules);
	_apply();

	$request->addResult('ok', 1);
	$request->setStatusDone();
}

sub clearCommand {
	my $request = shift;

	# Unlike set, clear does not require the player to be connected: a box
	# cleaning up a rule for a player that has since gone away (moved server,
	# removed) must be able to drop the stale rule from any server.
	my $mac = _macOf($request);
	unless ($mac) {
		return $request->setStatusBadParams();
	}

	my $rules = { %{ _rules() } };
	delete $rules->{$mac};
	$prefs->set('rules', $rules);
	_apply();

	$request->addResult('ok', 1);
	$request->setStatusDone();
}

sub statusQuery {
	my $request = shift;

	my $caps  = _capabilities();
	my $rules = _rules();

	$request->addResult('has_sox',    $caps->{sox}    ? 1 : 0);
	$request->addResult('has_sox_ng', $caps->{sox_ng} ? 1 : 0);
	$request->addResult('has_sdm',    $caps->{sdm}    ? 1 : 0);
	$request->addResult('dsd',        $caps->{sdm}    ? 1 : 0);   # DSD available here?
	$request->addResult('upsample',   $caps->{sox}    ? 1 : 0);   # PCM upsampling available?

	my $n = 0;
	for my $mac (sort keys %$rules) {
		my $r = $rules->{$mac};
		$request->addResultLoop('rules_loop', $n, 'mac',  $mac);
		$request->addResultLoop('rules_loop', $n, 'kind', $r->{kind});
		$request->addResultLoop('rules_loop', $n, 'a',    $r->{a});
		$request->addResultLoop('rules_loop', $n, 'b',    $r->{b});
		$n++;
	}
	$request->addResult('count', $n);

	$request->setStatusDone();
}

1;

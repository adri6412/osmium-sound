#!/usr/bin/env python3
"""Copies the kiosk's C++ sources from the Osmium Sound repository and adapts
the few places that only make sense on the appliance. Every replacement must
match exactly once, so a change upstream stops the build here instead of
producing a demo that silently behaves differently.

usage: prepare.py <osmium-sound checkout> <output dir>
"""
import os, shutil, sys

up, out = sys.argv[1], sys.argv[2]
# The appliance-served "Now Playing only" build (scripts/build-np.sh): the page
# always reaches the three services same-origin, and the device's webui_server
# resolves "follow another Lyrion" on its side (/device/lms → the real server).
# So the Qt side must pin the LMS base to the page origin (m_host), not m_lmsHost
# (which turns into a remote IP in follow mode and would break the proxy path).
NP_BUILD = os.environ.get("HIFI_NP_BUILD") == "1"
src = os.path.join(up, "native-ui-qt", "src")
shutil.rmtree(out, ignore_errors=True)
shutil.copytree(src, out)
# replaced by wasm/main.cpp; Bluetooth (D-Bus) and DRM do not exist in a browser
for f in ("main.cpp", "btghid.cpp", "btghid.h", "kmsmode.cpp", "kmsmode.h"):
    os.remove(os.path.join(out, f))


def patch(name, old, new):
    p = os.path.join(out, name)
    s = open(p, encoding="utf-8").read()
    if s.count(old) != 1:
        sys.exit(f"prepare.py: {name}: expected one match of {old[:70]!r}, found {s.count(old)}")
    open(p, "w", encoding="utf-8").write(s.replace(old, new))


# The three services answer inside the page (mock/device.js), at paths of the
# page's own origin instead of the appliance's ports.
patch("api.h", 'QString apiBase() const { return "http://" + m_host + ":8000"; }',
      'QString apiBase() const { return m_host + "/device/api"; }')
patch("api.h", 'QString srcBase() const { return "http://" + m_host + ":8080"; }',
      'QString srcBase() const { return m_host + "/device/src"; }')
patch("api.h", 'QString lmsBase() const { return "http://" + m_lmsHost + ":9000"; }',
      'QString lmsBase() const { return %s + "/device/lms"; }' % ("m_host" if NP_BUILD else "m_lmsHost"))
# the "host" is the page's origin (set in wasm/main.cpp through HIFI_HOST)
# The VU levels come from the audio the page is playing (Web Audio), not
# from the daemon's WebSocket.
patch("vumeter.h", "bool connected() const { return m_sock.state() == QAbstractSocket::ConnectedState && m_upgraded; }",
      "bool connected() const { return m_upgraded; }")
patch("vumeter.cpp", '#include <cmath>', '#include <cmath>\n#include <emscripten/val.h>')
patch("vumeter.cpp", """void VuMeter::connectWs() {
    m_sock.abort();
    m_sock.connectToHost(Api::instance()->host(), 9001);
    m_sock.setSocketOption(QAbstractSocket::LowDelayOption, 1);
}""", """void VuMeter::connectWs() {
    // demo: the levels of what the page is playing, read every 50 ms
    // (the daemon's own pace) from window.osmiumDevice.vuLevels()
    static QTimer *poll = nullptr;
    if (!poll) {
        poll = new QTimer(this);
        poll->setInterval(50);
        connect(poll, &QTimer::timeout, this, [this]() {
            if (!m_active) return;
            emscripten::val dev = emscripten::val::global("osmiumDevice");
            if (dev.isUndefined()) return;
            emscripten::val lv = dev.call<emscripten::val>("vuLevels");
            m_peak[0] = lv[0].as<double>();
            m_peak[1] = lv[1].as<double>();
        });
    }
    if (!m_upgraded) { m_upgraded = true; emit connectedChanged(); }
    poll->start();
}""")
# A static Qt build links only the QML modules the import scanner finds, and
# it only scans this project's own folder: list here every module the
# kiosk's QML imports (Hifi.* are registered in C++).
qml = os.path.join(up, "native-ui-qt", "qml")
imports = set()
for f in os.listdir(qml):
    if f.endswith(".qml"):
        for line in open(os.path.join(qml, f), encoding="utf-8"):
            line = line.strip()
            if line.startswith("import ") and not line.split()[1].startswith(("Hifi", '"')):
                imports.add(" ".join(line.split()[:2]))
here = os.path.dirname(os.path.abspath(__file__))
with open(os.path.join(here, "wasm", "imports.generated.qml"), "w", encoding="utf-8") as fh:
    fh.write("// generated by prepare.py: the QML modules of the kiosk, for the import scanner\n")
    fh.write("\n".join(sorted(imports)) + "\nItem {}\n")
print("prepare.py: sources ready in", out, "- QML modules:", ", ".join(sorted(i.split()[1] for i in imports)))
